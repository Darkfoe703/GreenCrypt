"""
GreenCrypt GUI subpackage (Qt front-end).

This package intentionally keeps its ``__init__`` light: importing
``greencrypt.gui`` must *not* pull in PySide6, so that environments without a
Qt binding can still import the package. The heavy import happens inside
:func:`main`, and the console-script entry point is ``greencrypt.gui:main``.

Layout::

    greencrypt/gui/
    ├── __init__.py    -> exposes main()          <- this file
    ├── app.py         -> the Qt code (MainWindow + main)
    ├── __main__.py    -> ``python -m greencrypt.gui``
    ├── main.ui        -> Qt Designer source
    ├── main_ui.py     -> generated by pyside6-uic (not committed)
    └── assets/        -> logo + window icon
"""

from __future__ import annotations


def main():
    """Build the ``QApplication`` and run the main window.

    The real implementation lives in :mod:`greencrypt.gui.app`; importing it
    here (lazily) means PySide6 is only required when the GUI is actually run.
    """
    from .app import main as _main

    _main()


__all__ = ["main"]
